// ---- Encode ----------------------------------------------------------------------
const names = Object.keys(GLYPHS);
if (names.length > 256) throw new Error('too many glyphs');
const W = 256, H = Math.ceil(names.length / 15) * 16;
const px = new Uint8Array(W * H);
names.forEach((name, i) => {
  const rows = GLYPHS[name].trim().split('\n').map((r) => r.trim());
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error(`glyph ${name} is not 16 x 16`);
  const u0 = (i % 15) * 16, v0 = Math.floor(i / 15) * 16;
  rows.forEach((r, y) => [...r].forEach((c, x) => { px[(v0 + y) * W + u0 + x] = c === '#' ? 1 : c === '+' ? 2 : c === '-' ? 3 : 0; }));
});

// CLUT: 0 see-through, 1 white, 2 60 %, 3 30 % (the polygon colour tints them).
const to15 = (v) => { const c = v >> 3; return c | (c << 5) | (c << 10); };
const clut = [0, to15(248), to15(150), to15(76), ...Array(12).fill(0)];
const clutBytes = 12 + 32, imageBytes = 12 + (W / 2) * H;
const tim = Buffer.alloc(8 + clutBytes + imageBytes);
tim.writeUInt32LE(0x10, 0);
tim.writeUInt32LE(0x08, 4);   // 4 bpp, has CLUT
let o = 8;
tim.writeUInt32LE(clutBytes, o); tim.writeUInt16LE(CLUT_X, o + 4); tim.writeUInt16LE(CLUT_Y, o + 6); tim.writeUInt16LE(16, o + 8); tim.writeUInt16LE(1, o + 10);
clut.forEach((c, i) => tim.writeUInt16LE(c, o + 12 + i * 2));
o += clutBytes;
tim.writeUInt32LE(imageBytes, o); tim.writeUInt16LE(TPAGE_X, o + 4); tim.writeUInt16LE(TPAGE_Y, o + 6); tim.writeUInt16LE(W / 4, o + 8); tim.writeUInt16LE(H, o + 10);
o += 12;
for (let i = 0; i < W * H; i += 2) tim[o + (i >> 1)] = px[i] | (px[i + 1] << 4);
writeFileSync(path.join(root, 'assets', 'glyphs.tim'), tim);

writeFileSync(path.join(root, 'src', 'glyphs.h'), `/* Generated by tools/makeglyphs.mjs: do not edit. */
#pragma once
#define GLYPH_TPAGE_X ${TPAGE_X}
#define GLYPH_TPAGE_Y ${TPAGE_Y}
#define GLYPH_CLUT_X  ${CLUT_X}
#define GLYPH_CLUT_Y  ${CLUT_Y}
enum {
${names.map((n, i) => `\tG_${n} = ${i},`).join('\n')}
\tNUM_GLYPHS
};
`);
console.log(`glyphs.tim: ${names.length} glyphs`);
