#!/usr/bin/env node
// Draws the game's glyphs (16 x 16 pixel art) into assets/glyphs.tim, a
// 4-bit texture with a grey CLUT so the game can tint each glyph with the
// polygon colour (per floor palettes), and writes src/glyphs.h with their ids.
//
//   node tools/makeglyphs.mjs
//
// Pixels: '#' full, '+' 60 %, '-' 30 %, anything else empty (see-through).
// Layout: 15 glyphs a row (u + 16 must stay under 256 for the GPU) in a
// 256-pixel texture page at VRAM (GLYPH_X, GLYPH_Y); glyph i at
// u = (i % 15) * 16, v = (i / 15) * 16. Glyphs that
// point somewhere (arrow, slash) point up; the game turns them.
